export function glyphColumns(character: string) {
  const rows = SHAPES[character.toUpperCase()] ?? SHAPES[' '];
  const columns = [0, 0, 0, 0, 0];
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x += 1) if (row[x] === '#') columns[x] |= 1 << y;
  });
  return columns;
}
